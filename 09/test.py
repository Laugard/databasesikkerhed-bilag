from session import Session
L.prepare()
L.start()
a=Session(L,'lab_skriver')
b=Session(L,'lab_laeser')
def balance(who):
    return "SELECT saldo FROM konti WHERE navn='Konto "+who+"';"
def change(who,expr):
    return "UPDATE konti SET saldo="+expr+" WHERE navn='Konto "+who+"';"
check(a.q(balance('A'))=='1000.00','Startsaldo')
a.q('BEGIN;\n'+change('A','saldo-100')+'\nCOMMIT;')
check(b.q(balance('A'))=='900.00','Commit')
a.q('BEGIN;\n'+change('A','saldo-500'))
check(a.q(balance('A'))=='400.00','Egen ændring')
a.q('ROLLBACK;')
check(b.q(balance('A'))=='900.00','Rollback')
a.q('BEGIN;\n'+change('B','0'))
b.q('BEGIN ISOLATION LEVEL READ COMMITTED;')
check(b.q(balance('B'))=='1000.00','Ucommittet beløb')
L.sql("SELECT pid,application_name,state,xact_start FROM pg_stat_activity WHERE application_name IN ('lab_skriver','lab_laeser');",expect='idle in transaction')
a.q('COMMIT;')
check(b.q(balance('B'))=='0.00','Nyt statement-snapshot')
b.q('COMMIT;')
a.q(change('B','5'))
b.q('BEGIN ISOLATION LEVEL REPEATABLE READ;')
check(b.q(balance('B'))=='5.00','Første snapshot')
a.q(change('B','25'))
check(b.q(balance('B'))=='5.00','Samme snapshot')
b.q('COMMIT;')
check(b.q(balance('B'))=='25.00','Ny transaktion')
a.q('BEGIN;\n'+change('A','saldo-10')+'\nSAVEPOINT delbelob;\n'+change('A','saldo-9999'))
check(a.q(balance('A'))=='-9109.00','Inden delvis rollback')
a.q('ROLLBACK TO delbelob;\nCOMMIT;')
check(b.q(balance('A'))=='890.00','Savepoint')
check(a.close()==0 and b.close()==0,'Klientafslutning')
L.sql("SELECT count(*) FROM pg_stat_activity WHERE application_name LIKE 'lab_%' AND xact_start IS NOT NULL;",expect='^0$')
